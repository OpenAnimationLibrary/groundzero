"""Render the MCP capability census document and the README tool index from census data."""

from __future__ import annotations

import textwrap
from typing import Any

README_BEGIN = "<!-- tool-index:begin (generated by ci-scripts/mcp_census.py) -->"
README_END = "<!-- tool-index:end -->"
CLASS_TITLES = {
    "exposed": "Exposed",
    "compositional": "Compositional",
    "optional": "Optional",
    "not_exposed": "Not exposed",
    "restricted": "Restricted",
    "unsupported": "Unsupported",
}
ORIGIN_TITLES = {
    "worker": "Native worker",
    "adapter": "Adapter",
    "live_bridge": "Live editor bridge",
}
TOOLSET_ORDER = ("core",)


def replace_region(readme: str, body: str) -> str:
    """Replace the generated tool index, or append it before the repository checks."""
    block = f"{README_BEGIN}\n{body}{README_END}"
    if README_BEGIN in readme:
        head, _, rest = readme.partition(README_BEGIN)
        _, _, tail = rest.partition(README_END)
        return head + block + tail
    heading = "## Repository checks"
    head, marker, tail = readme.partition(heading)
    return f"{head}## Tool index\n\n{block}\n\n{marker}{tail}"


def _names(tools: dict[str, dict[str, Any]], **match: Any) -> list[str]:
    return sorted(
        name
        for name, entry in tools.items()
        if all(entry[key] == value for key, value in match.items())
    )


def _toolset_names(tools: dict[str, dict[str, Any]]) -> list[str]:
    found = {entry["toolset"] for entry in tools.values() if entry["origin"] == "worker"}
    return sorted(found, key=lambda name: (name not in TOOLSET_ORDER, name))


def _bullet(label: str, names: list[str]) -> str:
    listed = ", ".join(f"`{name}`" for name in names)
    body = textwrap.fill(
        listed,
        width=96,
        initial_indent="  ",
        subsequent_indent="  ",
        break_on_hyphens=False,
        break_long_words=False,
    )
    return f"- {label}:\n{body}"


def render_readme_index(census: dict[str, Any]) -> str:
    """List every tool by toolset, followed by the adapter and live tools."""
    tools = census["tools"]
    lines = [
        "Every tool a session can advertise. Worker tools belong to the toolset named here;",
        "the adapter and the live editor bridge add the rest.",
        "",
    ]
    for toolset in _toolset_names(tools):
        names = _names(tools, origin="worker", toolset=toolset)
        lines.append(_bullet(f"`{toolset}` toolset ({len(names)})", names))
    lines.append(_bullet("Adapter", _names(tools, origin="adapter")))
    lines.append(_bullet("Live editor bridge", _names(tools, origin="live_bridge")))
    return "\n".join(lines) + "\n"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return lines + [""]


def _code(names: list[str]) -> str:
    return ", ".join(f"`{name}`" for name in names) or "none"


def _disposition(outcome: dict[str, Any]) -> str:
    disposition = outcome["disposition"]
    kind = disposition["kind"]
    if kind == "planned":
        return f"planned, {disposition['milestone']}"
    if kind in {"restricted", "unsupported"}:
        return f"{kind}: {disposition['reason']}"
    if "requires" in outcome:
        return f"implemented; requires {outcome['requires']}"
    return "implemented"


def _measures(counts: dict[str, Any]) -> list[str]:
    implemented = counts["implemented"]
    lines = [
        "## Measures",
        "",
        "These three counts are separate. A fully classified inventory does not mean every",
        "outcome is automated, and a tool with a listed test is not a platform qualification.",
        "",
    ]
    rows = [
        ["Outcomes inventoried and classified", str(counts["inventoried"])],
        ["Outcomes implemented by at least one tool", str(implemented)],
        ["Implemented outcomes whose every tool has a listed test", str(counts["tested"])],
        ["Tools in the catalog, adapter and live bridge", str(counts["tools"])],
        ["Tools without a listed test", str(len(counts["tools_without_tests"]))],
    ]
    lines += _table(["Measure", "Count"], rows)
    lines.append(f"Platform qualification: {counts['platforms']['summary']}.")
    lines.append("")
    return lines


def _classification_section(counts: dict[str, Any]) -> list[str]:
    rows = [[CLASS_TITLES[name], str(count)] for name, count in counts["by_classification"].items()]
    return ["## Outcomes by classification", ""] + _table(["Classification", "Outcomes"], rows)


def _toolset_section(census: dict[str, Any]) -> list[str]:
    tools = census["tools"]
    rows = []
    for origin, title in ORIGIN_TITLES.items():
        groups = sorted({entry["toolset"] for entry in tools.values() if entry["origin"] == origin})
        for toolset in groups:
            names = _names(tools, origin=origin, toolset=toolset)
            writers = [name for name in names if tools[name]["writes"]]
            untested = [name for name in names if not tools[name]["tests"]]
            rows.append(
                [title, f"`{toolset}`", str(len(names)), str(len(writers)), str(len(untested))]
            )
    header = ["Origin", "Toolset", "Tools", "Writing tools", "Without a listed test"]
    return ["## Tools by toolset", ""] + _table(header, rows)


def _outcome_section(census: dict[str, Any]) -> list[str]:
    lines = ["## Outcomes", ""]
    domains = list(dict.fromkeys(outcome["domain"] for outcome in census["outcomes"]))
    for domain in domains:
        rows = []
        for outcome in census["outcomes"]:
            if outcome["domain"] != domain:
                continue
            rows.append(
                [
                    f"`{outcome['id']}`",
                    outcome["outcome"],
                    CLASS_TITLES[outcome["classification"]],
                    _code(outcome["tools"]),
                    _disposition(outcome),
                ]
            )
        header = ["Outcome", "Description", "Class", "Tools", "Disposition"]
        lines += [f"### {domain}", ""] + _table(header, rows)
    return lines


def _tool_section(census: dict[str, Any]) -> list[str]:
    rows = []
    for name, entry in sorted(census["tools"].items()):
        tests = "<br>".join(f"`{test}`" for test in entry["tests"]) or "none listed"
        kind = "writes" if entry["writes"] else "reads"
        rows.append([f"`{name}`", entry["toolset"], kind, tests])
    lines = [
        "## Tools and their tests",
        "",
        "Each list names up to four acceptance tests, the revision-matrix test of a writing",
        "tool, two native test files, one adapter test and one script that call the tool most",
        "often. A test that only sets up a scene still counts.",
        "",
    ]
    return lines + _table(["Tool", "Toolset", "Kind", "Tests"], rows)


def _format_section(census: dict[str, Any]) -> list[str]:
    rows = []
    for entry in census["formats"]:
        evidence = entry["evidence"] if entry["state"] == "supported" else entry["reason"]
        shown = evidence if isinstance(evidence, str) else _evidence_text(evidence)
        rows.append([entry["id"], entry["role"], entry["state"], shown])
    lines = [
        "## File formats",
        "",
        "A supported format names the catalog entry that shows it. A refused format is one the",
        "README mentions only to say that it is rejected.",
        "",
    ]
    return lines + _table(["Format", "Role", "State", "Catalog evidence or reason"], rows)


def _evidence_text(evidence: dict[str, Any]) -> str:
    if evidence["kind"] == "enum":
        return f"`{evidence['tool']}` accepts {evidence['property']} `{evidence['value']}`"
    if evidence["kind"] == "description":
        return f"`{evidence['tool']}` describes {evidence['text']}"
    return f"`{evidence['tool']}` is in the catalog"


def _gap_section(census: dict[str, Any]) -> list[str]:
    rows = []
    for outcome in census["outcomes"]:
        if outcome["disposition"]["kind"] != "implemented":
            rows.append(
                [
                    f"`{outcome['id']}`",
                    CLASS_TITLES[outcome["classification"]],
                    _disposition(outcome),
                ]
            )
    lines = ["## Outcomes without an implementation", ""]
    return lines + _table(["Outcome", "Class", "Disposition"], rows)


def _untested_section(counts: dict[str, Any]) -> list[str]:
    lines = ["## Tools without a listed test", ""]
    names = counts["tools_without_tests"]
    lines.append(_code(names) if names else "None.")
    return lines + [""]


def render_document(census: dict[str, Any], counts: dict[str, Any]) -> str:
    """Render the census as markdown with a byte-stable layout."""
    lines = [
        "# MCP capability census",
        "",
        "Generated by `ci-scripts/mcp_census.py --document` from `ci-scripts/mcp_census.json`.",
        "Edit the data file, never this document. CI fails when this document is stale.",
        "",
        "An outcome is something an artist wants done. A tool is one typed operation. One outcome",
        "can need several tools, and one tool can serve several outcomes.",
        "",
    ]
    sections = [
        _measures(counts),
        _classification_section(counts),
        _toolset_section(census),
        _outcome_section(census),
        _gap_section(census),
        _tool_section(census),
        _format_section(census),
        _untested_section(counts),
    ]
    for section in sections:
        lines += section
    return "\n".join(lines).rstrip("\n") + "\n"
