"""Render the FX render compatibility matrix document from its data."""

from __future__ import annotations

from collections import Counter
from typing import Any

HEADER = """# FX render compatibility matrix

Generated by `ci-scripts/mcp_fx_matrix.py` from `ci-scripts/mcp_fx_matrix.json`; do not edit.
The static layer regenerates this document and fails when it differs, so it cannot go stale.
"""

READING = """## How to read this

Each cell is one admitted FX type rendered to one output format on one platform. Four outcomes
are kept apart and never summed into "supported":

- **passed**: a recorded run rendered the cell through the worker, decoded the output
  independently, and its difference from the stored reference is within the tolerance the cell
  states;
- **failed**: a run rendered it and the output was wrong; the reason says how;
- **unavailable**: the platform could not run the cell (for example no media tools); the reason
  says what was missing;
- **not tested**: no run has covered the cell. Nothing is claimed about it.

A platform is labelled **complete** only when every one of its cells ran (none is not tested) and
every cell came from the platform's latest run. A run of part of the grid makes the platform
incomplete: the label is derived from the cells, and the check fails when the data states
otherwise. A run on one platform is no evidence about another.
"""


def _row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = [_row(header), _row(["---"] * len(header))]
    lines += [_row(row) for row in rows]
    return lines + [""]


def _cells(data: dict[str, Any]) -> list[tuple[str, str, str, dict[str, Any]]]:
    return [
        (kind, form, platform, cell)
        for kind, forms in data["cells"].items()
        for form, platforms in forms.items()
        for platform, cell in platforms.items()
    ]


def _summary(data: dict[str, Any], summaries: dict[str, dict[str, Any]]) -> list[str]:
    rows = []
    for platform, entry in data["platforms"].items():
        found = summaries[platform]
        counts: Counter[str] = found["counts"]
        rows.append(
            [
                platform,
                "complete" if found["complete"] else "incomplete",
                str(counts["passed"]),
                str(counts["failed"]),
                str(counts["unavailable"]),
                str(counts["not_tested"]),
                str(found["stale"]),
                entry.get("latest_run") or "none",
            ]
        )
    header = ["Platform", "Label", "Passed", "Failed", "Unavailable", "Not tested", "Older run"]
    return ["## Platforms", ""] + _table([*header, "Latest run"], rows)


def _identity_lines(name: str, run: dict[str, Any]) -> list[str]:
    identity = run["identity"]
    lines = [f"### Run `{name}` on {run['platform']}", "", f"- recorded: {run['recorded']}"]
    lines.append(f"- reason: {run['reason']}")
    lines.append(f"- covered: {run['covered']}")
    for key, value in identity.items():
        lines.append(f"- {key}: `{value}`")
    return lines + [""]


def _runs(data: dict[str, Any]) -> list[str]:
    lines = ["## Recorded runs", ""]
    if not data["runs"]:
        return lines + ["No run is recorded.", ""]
    for name, run in data["runs"].items():
        lines += _identity_lines(name, run)
    return lines


def _tolerances(data: dict[str, Any]) -> list[str]:
    rows = [
        [
            entry["id"],
            f"`{entry['job_format']}` ({entry['profile']})",
            entry["compared"],
            entry["cap"],
        ]
        for entry in data["formats"]
    ]
    return ["## Formats and the widest tolerance each may state", ""] + _table(
        ["Format", "Job format", "What is compared", "Cap"], rows
    )


def _grid(data: dict[str, Any], types: list[str]) -> list[str]:
    platforms = list(data["platforms"])
    lines = ["## Status by type", ""]
    header = ["FX type"]
    header += [f"{entry['id']} / {platform}" for entry in data["formats"] for platform in platforms]
    rows = []
    for kind in types:
        row = [f"`{kind}`"]
        for entry in data["formats"]:
            for platform in platforms:
                row.append(data["cells"][kind][entry["id"]][platform]["status"].replace("_", " "))
        rows.append(row)
    return lines + _table(header, rows)


def _measure(values: dict[str, Any]) -> str:
    return ", ".join(f"{name} {value}" for name, value in values.items() if name != "why")


def _measured(data: dict[str, Any], types: list[str]) -> list[str]:
    rows = []
    for kind in types:
        for form, platforms in data["cells"][kind].items():
            for platform, cell in platforms.items():
                if cell["status"] in {"passed", "failed"}:
                    rows.append(
                        [
                            f"`{kind}`",
                            form,
                            platform,
                            cell["status"],
                            _measure(cell["tolerance"]),
                            _measure(cell["observed"]),
                        ]
                    )
    lines = ["## Tolerance and observed difference of every cell that ran", ""]
    if not rows:
        return lines + ["No cell has run.", ""]
    header = ["FX type", "Format", "Platform", "Status", "Tolerance used", "Observed"]
    return lines + _table(header, rows)


def _unmeasured(data: dict[str, Any], types: list[str]) -> list[str]:
    groups: dict[tuple[str, str, str, str], list[str]] = {}
    for kind, form, platform, cell in _cells(data):
        if kind in types and cell["status"] not in {"passed"}:
            key = (cell["status"], form, platform, cell["reason"])
            groups.setdefault(key, []).append(kind)
    lines = ["## Cells that did not pass", ""]
    if not groups:
        return lines + ["Every cell passed.", ""]
    rows = [
        [status.replace("_", " "), form, platform, str(len(kinds)), reason]
        for (status, form, platform, reason), kinds in sorted(groups.items())
    ]
    return lines + _table(["Status", "Format", "Platform", "Cells", "Reason"], rows)


def _agreement(data: dict[str, Any], types: list[str]) -> list[str]:
    """Where recorded platforms render a type differently: a difference is shown, not toleranced."""
    lines = ["## Agreement between platforms", ""]
    recorded = [
        platform
        for platform in data["platforms"]
        if any(
            data["cells"][kind]["png_sequence"][platform]["status"] == "passed" for kind in types
        )
    ]
    if len(recorded) < 2:
        return lines + [
            "References are kept per platform and compared exactly on that platform. Fewer than "
            "two "
            f"platforms have recorded PNG references ({', '.join(recorded) or 'none'}), so no "
            "difference between platforms can be shown yet.",
            "",
        ]
    rows = []
    for kind in types:
        digests = {
            platform: data["cells"][kind]["png_sequence"][platform].get("reference", "")[:12]
            for platform in recorded
        }
        if len(set(digests.values())) > 1:
            rows.append([f"`{kind}`", ", ".join(f"{p} {d}" for p, d in digests.items())])
    if not rows:
        return lines + [f"Every type renders the same PNG pixels on {', '.join(recorded)}.", ""]
    return lines + _table(["FX type", "Reference digests that differ"], rows)


def _gaps(data: dict[str, Any]) -> list[str]:
    lines = ["## Released tools without a negative test", ""]
    gaps = data["negative_test_gaps"]
    if not gaps:
        return lines + ["Every released tool has a negative test.", ""]
    lines += [
        "A tool listed here has no acceptance case that calls it expecting a refusal. The check "
        "fails when a tool lacks one and is not listed, and when a listed tool gains one.",
        "",
    ]
    return lines + _table(
        ["Tool", "Why there is none"], [[f"`{t}`", r] for t, r in sorted(gaps.items())]
    )


def render_document(
    data: dict[str, Any], types: list[str], summaries: dict[str, dict[str, Any]]
) -> str:
    """The matrix document for the data, as markdown text."""
    sections = [
        [HEADER],
        [READING],
        _summary(data, summaries),
        _tolerances(data),
        _grid(data, types),
        _measured(data, types),
        _unmeasured(data, types),
        _agreement(data, types),
        _runs(data),
        _gaps(data),
    ]
    return "\n".join("\n".join(section) for section in sections).rstrip() + "\n"
