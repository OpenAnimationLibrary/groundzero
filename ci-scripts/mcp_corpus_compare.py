"""The old-scene corpus: its manifest, the check that keeps its baselines honest, and the compare.

`ci-scripts/fixtures/corpus/` holds small scenes, each in its own project, and for each scene the
frames that a reference renderer wrote for it, the baselines. `manifest.json` records, for every
file, its SHA-256; for every baseline, the scene files it was rendered from; for the set of
baselines, one hash; and in `history`, every time the baselines were deliberately regenerated, with
the reason. This module has no way to write a baseline. `mcp_corpus_build.py` does, only on request
and only with a reason.

The default command checks the corpus without a worker and is part of the static layer:

- a scene or baseline file that differs from the manifest, is missing or is not listed fails;
- a baseline rendered from scene files that have since changed fails;
- baselines whose set hash has no matching entry in `history` fail, so they cannot be replaced
  quietly;
- a comparison policy must be valid (see `mcp_native_oracle.Policy`);
- the effects a scene declares must be the effects its scene file holds;
- every probe (a pixel the construction of the scene says must hold a value, or an effect that
  must change a pixel between two frames) must hold in the baselines, and the corpus as a whole
  must show a vector column, a Toonz raster column, a PNG column and an animated effect in its
  baselines: a scene whose columns are all hidden under an opaque PNG proves nothing about them.

`compare SCENE FOLDER` compares a folder of rendered frames with a scene's baselines. A missing
baseline or a missing frame is a failure, never a pass and never a new baseline.

Provenance: no artist-made scene and no build older than this one exists to draw on, so the scenes
are generated by script and the baselines come from the batch renderer of the same build as the
candidate. The manifest says so; it is a regression net for later changes, not evidence about an
earlier release.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any

from mcp_native_oracle import Difference, OracleError, Policy, compare_files, decode_file

SCRIPTS = Path(__file__).resolve().parent
CORPUS = SCRIPTS / "fixtures" / "corpus"
MANIFEST = CORPUS / "manifest.json"
BASELINES = CORPUS / "baselines"
SCHEMA_VERSION = 1
MINIMUM_REASON = 20
PROVENANCE_KINDS = {"generated_by_script"}
PROBE_KINDS = ("vector", "toonz_raster", "png", "background", "effect")
REQUIRED_PROBE_KINDS = ("vector", "toonz_raster", "png", "effect")
MINIMUM_EFFECT_TYPES = 6
COMPARISONS = ("bridge_disabled", "bridge_enabled", "assisted_save_reopen")
EFFECT_TAG = re.compile(r"<([A-Za-z][A-Za-z0-9_]*Fx) id='\d+'>")
STRUCTURAL_PREFIX = "Toonz_"


def sha256_file(path: Path) -> str:
    """The SHA-256 of a file's bytes."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def digest(pairs: dict[str, str]) -> str:
    """One hash for a set of named hashes, independent of order."""
    text = "".join(f"{name}\0{value}\n" for name, value in sorted(pairs.items()))
    return hashlib.sha256(text.encode()).hexdigest()


def load_manifest(path: Path = MANIFEST) -> dict[str, Any]:
    """Read the manifest."""
    return json.loads(path.read_text(encoding="utf-8"))


def dump_manifest(manifest: dict[str, Any]) -> str:
    """Serialize the manifest with a stable layout."""
    return json.dumps(manifest, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def scene_files(root: Path, name: str) -> dict[str, str]:
    """Every file of one scene's project, by path relative to the project, with its hash."""
    folder = root / name
    return {
        str(path.relative_to(folder)): sha256_file(path)
        for path in sorted(folder.rglob("*"))
        if path.is_file()
    }


def baseline_files(root: Path, name: str) -> dict[str, str]:
    """Every baseline frame of one scene, by file name, with its hash."""
    folder = root / "baselines" / name
    if not folder.is_dir():
        return {}
    return {path.name: sha256_file(path) for path in sorted(folder.glob("*.png"))}


def baseline_set(manifest: dict[str, Any]) -> str:
    """The hash of every baseline the manifest lists."""
    pairs = {
        f"{name}/{frame}": value
        for name, scene in manifest["scenes"].items()
        for frame, value in scene["baseline"]["files"].items()
    }
    return digest(pairs)


def policy_of(scene: dict[str, Any]) -> Policy:
    """The comparison policy a scene declares."""
    return Policy(**scene["policy"])


def scene_effects(root: Path, name: str) -> list[str]:
    """The effect types a scene's file declares, without the nodes the scene always has."""
    text = (root / name / "scenes" / "shot.tnz").read_text(encoding="utf-8")
    return sorted(
        {tag for tag in EFFECT_TAG.findall(text) if not tag.startswith(STRUCTURAL_PREFIX)}
    )


def _pixel(root: Path, name: str, frame: int, x: int, y: int) -> tuple[int, int, int, int]:
    width, _height, pixels = decode_file(root / "baselines" / name / f"frame.{frame + 1:04d}.png")
    return pixels[y * width + x]


def _probe_problems(
    root: Path, name: str, scene: dict[str, Any], manifest: dict[str, Any]
) -> list[str]:
    """Check each probe of a scene against its baselines."""
    found = []
    window, size = manifest["frames"], manifest["frames"]["width"]
    for index, probe in enumerate(scene.get("probes", [])):
        where = f"{name} probe {index} ({probe.get('what', 'no description')})"
        frames = probe.get("frames") or [probe.get("frame")]
        if probe.get("kind") not in PROBE_KINDS or not probe.get("what", "").strip():
            found.append(f"{where}: needs a kind of {list(PROBE_KINDS)} and a description")
            continue
        if not all(isinstance(f, int) and window["first"] <= f <= window["last"] for f in frames):
            found.append(f"{where}: frame outside the baselines")
            continue
        if not (0 <= probe["x"] < size and 0 <= probe["y"] < window["height"]):
            found.append(f"{where}: pixel outside the image")
            continue
        try:
            found += [f"{where}: {problem}" for problem in _probe_value(root, name, probe, frames)]
        except OracleError as error:
            found.append(f"{where}: {error}")
    return found


def _probe_value(root: Path, name: str, probe: dict[str, Any], frames: list[int]) -> list[str]:
    here = [_pixel(root, name, frame, probe["x"], probe["y"]) for frame in frames]
    if "min_difference" in probe:
        gap = max(abs(here[0][i] - here[1][i]) for i in range(4)) if len(here) == 2 else -1
        if gap < probe["min_difference"]:
            return [
                f"the pixel changes by {gap} between frames {frames}, not {probe['min_difference']}"
            ]
        return []
    if tuple(probe["rgba"]) != here[0]:
        return [f"the baseline holds {list(here[0])} at the pixel, not {probe['rgba']}"]
    return []


def _comparison_problems(manifest: dict[str, Any]) -> list[str]:
    """Each comparison the corpus is meant to support is either backed by cases or says why not."""
    cases = (SCRIPTS / "mcp_corpus_cases.py").read_text(encoding="utf-8")
    found = []
    stated = manifest.get("comparisons", {})
    for name in COMPARISONS:
        entry = stated.get(name)
        if entry is None:
            found.append(f"comparisons: no statement for {name}")
        elif entry.get("status") == "compared":
            found += [
                f"comparisons {name}: names case {case}, which mcp_corpus_cases.py does not define"
                for case in entry.get("cases", []) or [""]
                if f"def {case}(" not in cases
            ]
        elif entry.get("status") == "not_built":
            if len(entry.get("reason", "").strip()) < MINIMUM_REASON * 2:
                found.append(f"comparisons {name}: not built, and the reason is missing or short")
        else:
            found.append(f"comparisons {name}: status must be compared or not_built")
    return found


def _coverage_problems(manifest: dict[str, Any]) -> list[str]:
    """The corpus must show every kind of column, and animated effects, in its baselines."""
    scenes = manifest["scenes"].values()
    kinds = {probe["kind"] for scene in scenes for probe in scene.get("probes", [])}
    found = [
        f"no probe shows a {kind} in a baseline: the corpus would not notice it vanish"
        for kind in REQUIRED_PROBE_KINDS
        if kind not in kinds
    ]
    types = {kind for scene in scenes for kind in scene.get("effects", [])}
    if len(types) < MINIMUM_EFFECT_TYPES:
        found.append(f"the scenes use {len(types)} effect types, fewer than {MINIMUM_EFFECT_TYPES}")
    animated = [p for scene in scenes for p in scene.get("probes", []) if "frames" in p]
    if not animated:
        found.append("no probe shows an effect changing a pixel between frames")
    return found


def _scene_problems(
    root: Path, name: str, scene: dict[str, Any], frames: int, manifest: dict[str, Any]
) -> list[str]:
    found = []
    actual = scene_files(root, name)
    for path in sorted(set(scene["files"]) | set(actual)):
        if path not in actual:
            found.append(f"{name}: {path} is listed but missing")
        elif path not in scene["files"]:
            found.append(f"{name}: {path} is not listed in the manifest")
        elif actual[path] != scene["files"][path]:
            found.append(f"{name}: {path} differs from the manifest")
    if digest(scene["files"]) != scene["scene_sha256"]:
        found.append(f"{name}: scene_sha256 does not match its file list")
    found += [f"{name}: {reason}" for reason in policy_of(scene).problems()]
    found += _baseline_problems(root, name, scene, frames)
    declared = scene.get("effects", [])
    if declared != scene_effects(root, name):
        found.append(
            f"{name}: declares effects {declared}, its scene file holds {scene_effects(root, name)}"
        )
    found += _probe_problems(root, name, scene, manifest)
    return found


def _baseline_problems(root: Path, name: str, scene: dict[str, Any], frames: int) -> list[str]:
    baseline = scene["baseline"]
    actual = baseline_files(root, name)
    found = []
    if len(baseline["files"]) != frames:
        found.append(f"{name}: {len(baseline['files'])} baseline frames listed, {frames} needed")
    for frame in sorted(set(baseline["files"]) | set(actual)):
        if frame not in actual:
            found.append(f"{name}: baseline {frame} is missing; a missing reference is a failure")
        elif frame not in baseline["files"]:
            found.append(f"{name}: baseline {frame} is not listed in the manifest")
        elif actual[frame] != baseline["files"][frame]:
            found.append(f"{name}: baseline {frame} changed without regeneration")
    if baseline["rendered_from"] != scene["scene_sha256"]:
        found.append(
            f"{name}: the scene files changed after its baselines were rendered; regenerate "
            "them deliberately with mcp_corpus_build.py baselines --reason"
        )
    return found


def _history_problems(manifest: dict[str, Any]) -> list[str]:
    history = manifest.get("history", [])
    if not history:
        return ["history has no entry: baselines need a recorded generation"]
    last = history[-1]
    found = []
    if last["baseline_set_sha256"] != baseline_set(manifest):
        found.append(
            "the baselines differ from the last entry of history: they were replaced without "
            "a recorded, reasoned regeneration"
        )
    for entry in history:
        if len(entry.get("reason", "").strip()) < MINIMUM_REASON:
            found.append(f"history entry {entry.get('when')}: the reason is missing or too short")
    return found


def check(root: Path = CORPUS) -> list[str]:
    """Return every way the corpus is not what its manifest says; no worker is needed."""
    path = root / "manifest.json"
    if not path.is_file():
        return [f"{path} does not exist; build the corpus with mcp_corpus_build.py"]
    manifest = load_manifest(path)
    found = []
    if manifest.get("schema_version") != SCHEMA_VERSION:
        found.append(f"schema_version must be {SCHEMA_VERSION}")
    if manifest.get("provenance", {}).get("kind") not in PROVENANCE_KINDS:
        found.append(f"provenance.kind must be one of {sorted(PROVENANCE_KINDS)}")
    window = manifest["frames"]
    count = window["last"] - window["first"] + 1
    present = sorted(entry.name for entry in root.iterdir() if entry.is_dir())
    expected = sorted(["baselines", *manifest["scenes"]])
    found += [
        f"{name}: a folder that the manifest does not list"
        for name in present
        if name not in expected
    ]
    for name, scene in manifest["scenes"].items():
        found += _scene_problems(root, name, scene, count, manifest)
    found += _coverage_problems(manifest) + _comparison_problems(manifest)
    return found + _history_problems(manifest)


def compare_scene(
    manifest: dict[str, Any], name: str, rendered: list[Path], root: Path = CORPUS
) -> list[str]:
    """Compare rendered frames, in order, with a scene's baselines under the scene's policy.

    A scene with no baseline, or a frame without its baseline file, is a failure.
    """
    scene = manifest["scenes"].get(name)
    if scene is None:
        return [f"{name}: not in the corpus"]
    names = sorted(scene["baseline"]["files"])
    if len(rendered) != len(names):
        return [f"{name}: {len(rendered)} frames rendered, {len(names)} baselines"]
    problems = []
    for baseline, image in zip(names, rendered, strict=True):
        reference = root / "baselines" / name / baseline
        try:
            difference = compare_files(reference, image, policy_of(scene))
        except OracleError as error:
            problems.append(f"{name} {baseline}: {error}")
            continue
        problems += [f"{name} {baseline}: {problem}" for problem in difference.problems]
    return problems


def describe(difference: Difference) -> str:
    """One line on what differs, for a report."""
    return (
        f"{difference.differing} pixels, color {difference.max_color}, alpha "
        f"{difference.max_alpha}, within {difference.box}"
    )


def main() -> int:
    """Check the corpus, or compare a folder of frames with one scene's baselines."""
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command")
    commands.add_parser("check", help="check the corpus against its manifest (the default)")
    compare = commands.add_parser("compare", help="compare rendered frames with baselines")
    compare.add_argument("scene")
    compare.add_argument("folder", type=Path)
    arguments = parser.parse_args()
    if arguments.command == "compare":
        frames = sorted(arguments.folder.glob("*.png"))
        problems = compare_scene(load_manifest(), arguments.scene, frames)
    else:
        problems = check()
        if MANIFEST.is_file():
            manifest = load_manifest()
            count, digest_text = len(manifest["scenes"]), baseline_set(manifest)[:12]
            print(f"corpus: {count} scenes; baseline set {digest_text}")
    for problem in problems:
        print(f"corpus: {problem}")
    return int(bool(problems))


if __name__ == "__main__":
    sys.exit(main())
